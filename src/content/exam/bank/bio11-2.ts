function build(chapter: string, no: number, list: Q[]): ExamQuestion[] {
  return list.map(
    (it, i): ExamQuestion => ({
      id: `bio11-2-${String(no).padStart(2, "0")}-${String(i + 1).padStart(3, "0")}`,
      subject: "biology",
      chapter,
      grade: "11",
      exams: it.x ?? ["NEET", "KCET"],
      kind: "mcq",
      difficulty: it.d,
      idealTime: it.t,
      q: it.q,
      options: it.o,
      answer: it.a,
      explain: it.e,
      ...(it.h ? { hint: it.h } : {}),
    }),
  );
}

